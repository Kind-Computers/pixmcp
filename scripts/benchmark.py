"""Run deterministic PIX investigations and record correctness, calls, bytes and replay jobs.

python scripts/benchmark.py <server.exe> --capture baseline.wpix [--candidate candidate.wpix]
Use D3D12TestApp --variant baseline/candidate --hidden to produce the fixtures.
No applications are launched and no GPU hangs are generated by this benchmark.

The report starts with an environment block (scripts/environment.py). Each task records its own tool calls; the pix_jobs
inventory taken after it is overhead. scripts/benchmark-budgets.json caps calls and returned JSON bytes per task and the
wire-to-JSON ratio per text mode; --enforce-budgets fails a run more than 10 % over a budget. --baseline PREVIOUS.json marks
tasks whose calls or bytes grew by more than 25 %.
"""
import argparse
import json
import os
from pathlib import Path
import sys
import tempfile
import time

from smoke import Client, SmokeError

BUDGETS = Path(__file__).resolve().parent / "benchmark-budgets.json"
BUDGET_SLACK = 0.10
REGRESSION_THRESHOLD = 0.25


class Investigator:
    def __init__(self, client):
        self.client = client
        self.calls = []
        self.replay_jobs = set()

    def call(self, tool, **arguments):
        started = time.monotonic()
        response = None
        error = None
        self.client.last_response_bytes = 0
        try:
            response = self.client.call(tool, arguments)
        except Exception as caught:
            error = f"{type(caught).__name__}: {caught}"
            raise
        finally:
            self.calls.append({"tool": tool, "seconds": time.monotonic() - started,
                               "returnedJsonBytes": 0 if response is None else len(json.dumps(response, ensure_ascii=False).encode("utf-8")),
                               "returnedWireBytes": getattr(self.client, "last_response_bytes", None),
                               **({"error": error} if error else {})})
        if isinstance(response, dict):
            job = response.get("job", response)
            self.observe_job(job)
        return response

    def observe_job(self, job):
        if job.get("kind") in {"analysis", "timing", "counters", "occupancy", "hf-counters",
                               "accessed-resources", "resource-uses", "shader-index", "event-inspection", "capture-compare", "preview"}:
            if job.get("jobId"):
                self.replay_jobs.add(job["jobId"])

    def read(self, reference, pointer=""):
        offset = 0
        combined = None
        while True:
            page = self.call("pix_result_read", resultRef=reference, pointer=pointer, offset=offset, limit=1000)
            if page["kind"] == "array":
                if combined is None:
                    combined = []
                combined.extend(self.expand(value, reference) for value in page["value"])
            elif page["kind"] == "object":
                if combined is None:
                    combined = {}
                combined.update((key, self.expand(value, reference)) for key, value in page["value"].items())
            elif page["kind"] == "string":
                combined = (combined or "") + page["value"]
            else:
                return page.get("value")
            if "nextOffset" not in page:
                return combined
            if page["nextOffset"] <= offset:
                raise SmokeError("Result continuation made no progress")
            offset = page["nextOffset"]

    def expand(self, value, reference):
        if isinstance(value, dict) and value.get("deferred") is True and "pointer" in value:
            return self.read(reference, value["pointer"])
        return value

    def wait(self, job):
        for _ in range(30):
            if job.get("status") in {"succeeded", "failed", "cancelled"}:
                if job["status"] != "succeeded":
                    raise SmokeError(f"Job failed: {job}")
                return job
            job = self.call("pix_job_wait", jobId=job["jobId"], timeoutSeconds=30)
        raise SmokeError("Job did not finish within the benchmark deadline")

    def query(self, tool, **arguments):
        """Runs a query to its final answer. answer_bytes records the size of that answer: a deferred
        result counts its totalBytes (the JSON the tool produced), an inline one its returned JSON."""
        self.answer_bytes = None
        for _ in range(10):
            try:
                response = self.call(tool, **arguments)
            except SmokeError as error:
                if not self.recover_worker_busy(error, tool, arguments):
                    raise
                continue
            if isinstance(response, dict) and response.get("pending"):
                self.wait(response)
                continue
            section = self.pending_section(response)
            if section is not None:
                self.wait(section)
                continue
            if isinstance(response, dict) and "jobId" in response:
                return self.read(self.wait(response)["resultRef"])
            if isinstance(response, dict) and response.get("deferred"):
                self.answer_bytes = response.get("totalBytes")
                return self.read(response["resultRef"])
            self.answer_bytes = self.calls[-1]["returnedJsonBytes"]
            return response
        raise SmokeError(f"{tool}: prerequisites did not become ready")

    @staticmethod
    def pending_section(response):
        """A partial answer carries metadata plus one pending section (timing, preparation, pipeline, bindings)."""
        if not isinstance(response, dict):
            return None
        for key in ("preparation", "timing", "pipeline", "bindings"):
            section = response.get(key)
            if isinstance(section, dict) and section.get("pending") and section.get("jobId"):
                return section
        return None

    def recover_worker_busy(self, error, tool, arguments):
        marker = "tool error: "
        if marker not in str(error):
            return False
        try:
            blocks = json.loads(str(error).split(marker, 1)[1])
        except (TypeError, ValueError):
            return False
        if not isinstance(blocks, list):
            return False
        detail = next((block for block in blocks if isinstance(block, dict) and
                       block.get("code") == "worker_busy" and block.get("retryable") is True), None)
        if detail is None:
            return False
        calls = detail.get("nextCalls", [])
        if not any(call.get("tool") == tool and call.get("arguments") == arguments for call in calls):
            return False
        waited = False
        for call in calls:
            if call.get("tool") == "pix_job_wait":
                self.call("pix_job_wait", **call["arguments"])
                waited = True
        if not waited:
            time.sleep(0.05)
        return True


def contains(value, wanted):
    if isinstance(value, dict):
        return any(contains(v, wanted) for v in value.values())
    if isinstance(value, list):
        return any(contains(v, wanted) for v in value)
    return value == wanted


def known_root_constant_limitation(coverage):
    # PIX's projected GetValue E_INVALIDARG becomes this ArgumentException on 2606.18;
    # the HRESULT is absent from that projection's error DTO. Do not excuse other errors.
    def known(item):
        if not isinstance(item, dict) or item.get("feature") != "rootConstants":
            return False
        error = item.get("error", {})
        return item.get("state") == "unsupported" or error.get("hresult") == "0x80070057" or (
            error.get("code") == "invalid_arguments" and
            error.get("message") == "ArgumentException: Value does not fall within the expected range.")
    return bool(coverage) and all(known(item) for item in coverage)


def new_report():
    return {"tasks": [], "limitations": [], "nativeReplayIterations": None,
            "measurementNote": "returnedJsonBytes measures decoded tool payload JSON with image data summarized. returnedWireBytes measures received UTF-8 JSON-RPC response lines, including image base64 and duplicated structured/text content. Calls include failed requests and a pix_jobs inventory after each attempted task. Replay jobs count tool-level preparations; PIX's internal replay iteration count is not exposed."}


class TaskRecorder:
    def __init__(self, agent, report):
        self.agent = agent
        self.report = report

    def task(self, name, work, available=True):
        if not available:
            self.report["tasks"].append({"name": name, "passed": False, "status": "skipped",
                                         "reason": "Required output from an earlier task is unavailable.",
                                         "seconds": 0, "toolCalls": 0, "returnedJsonBytes": 0,
                                         "returnedWireBytes": 0, "replayPreparationJobs": 0})
            return None
        first = len(self.agent.calls)
        jobs_before = set(self.agent.replay_jobs)
        limitations_before = len(self.report["limitations"])
        started = time.monotonic()
        result = None
        errors = []
        try:
            result = work()
        except Exception as error:
            errors.append(f"{type(error).__name__}: {error}")
        inventory_first = len(self.agent.calls)
        try:
            inventory = self.agent.query("pix_jobs")
            for job in inventory["items"]:
                self.agent.observe_job(job)
        except Exception as error:
            errors.append(f"Job inventory: {type(error).__name__}: {error}")
        calls = self.agent.calls[first:inventory_first]
        overhead = self.agent.calls[inventory_first:]
        limited = len(self.report["limitations"]) > limitations_before
        status = "failed" if errors else "limited" if limited else "passed"
        self.report["tasks"].append({"name": name, "passed": status == "passed", "status": status,
                                     "seconds": time.monotonic() - started, "errors": errors,
                                     "toolCalls": len(calls), "returnedJsonBytes": sum(c["returnedJsonBytes"] for c in calls),
                                     **({"detail": result["detail"]} if isinstance(result, dict) and "detail" in result else {}),
                                     "returnedWireBytes": sum(c["returnedWireBytes"] or 0 for c in calls),
                                     "overhead": {"toolCalls": len(overhead), "returnedJsonBytes": sum(c["returnedJsonBytes"] for c in overhead)},
                                     "replayPreparationJobs": len(self.agent.replay_jobs - jobs_before)})
        return result


def run(client, capture, candidate=None, report=None):
    agent = Investigator(client)
    report = report if report is not None else new_report()
    task = TaskRecorder(agent, report).task

    def require(condition, message):
        if not condition:
            raise SmokeError(message)

    opened = task("Open baseline capture", lambda: agent.query("pix_gpu_open", path=str(Path(capture).resolve())))
    handle = opened.get("handle") if opened else None
    def overview():
        value = agent.query("pix_gpu_overview", handle=handle)
        require(bool(value["queues"]) and bool(value["topDraws"]) and bool(value["topPasses"]), "Overview needs queues, timed draws and marker passes")
        require(value["capture"]["frames"]["count"] >= 1 and sum(b["count"] for b in value["histogram"]["buckets"]) == len(value["topDraws"]), "Overview v2 needs capture frames and an EOP histogram covering the work events")
        require(all(row["kind"] in ("draw", "dispatch", "executeIndirect") for row in value["topDraws"]), "topDraws must rank only work events")
        require(any(row["name"].endswith("Frame") for row in value["topPasses"]), "The fixture Frame marker must rank as a pass")
        require(agent.answer_bytes is not None and agent.answer_bytes < 12000, f"Overview answer is {agent.answer_bytes} bytes (budget 12000)")
        return value
    task("Find GPU hotspots", overview, handle is not None)
    def inspect():
        draw_page = agent.query("pix_gpu_events", handle=handle, kind="draw", limit=1)
        event_ref = draw_page["items"][0]["eventRef"]
        value = agent.query("pix_gpu_inspect_event", eventRef=event_ref)
        require(value["eventRef"] == event_ref, "Inspection changed the event reference")
        require(value.get("kind") == "draw" and (value.get("parameters") or {}).get("workItems") == 3, "Inspection v2 needs the draw kind and the parsed work items")
        require((value.get("timing") or {}).get("rankInQueue", 0) >= 1, "Inspection timing lacks rankInQueue")
        require((value.get("targets") or {}).get("state") == "available", "Inspection targets are not available for the fixture draw")
        if not contains(value, 0x50495831):
            coverage = (value.get("bindings") or {}).get("rootConstantCoverage", [])
            require(bool(coverage), "Known fixture root constant was not returned and has no unavailable evidence")
            require(known_root_constant_limitation(coverage), "Root constant failure is not an explicitly known native limitation: " + json.dumps(coverage))
            report["limitations"].append({"task": "Inspect a draw and actual root constants", "feature": "rootConstantValues",
                                          "reason": "PIX did not expose the known fixture DWORD values.", "coverage": coverage})
        return value
    inspected = task("Inspect a draw and actual root constants", inspect, handle is not None)
    def shader_navigation():
        shaders = inspected["pipeline"]["shaders"]
        shader_ref = next(s["shaderRef"] for s in shaders if "HLSL" in s.get("availableCode", []))
        value = agent.query("pix_gpu_shader_code", shaderRef=shader_ref, lineCount=1)
        require(value["count"] == 1 and "nextStartLine" in value, "Shader line continuation missing")
        tail = agent.query("pix_gpu_shader_code", shaderRef=shader_ref, startLine=value["nextStartLine"], lineCount=2)
        require(tail["startLine"] > value["startLine"], "Shader tail not reachable")
        matches = agent.query("pix_gpu_shader_search", shaderRef=shader_ref, query="float")
        require(matches["total"] > 0, "Shader search did not locate fixture source")
    task("Navigate and search shader code", shader_navigation, bool(inspected and inspected.get("pipeline")))
    def shader_inventory():
        value = agent.query("pix_gpu_shaders", handle=handle)
        require(value["total"] > 0, "Shader inventory is empty")
        shader_ref = value["items"][0]["shader"]["shaderRef"]
        uses = agent.query("pix_gpu_shader_uses", shaderRef=shader_ref)
        require(uses["total"] > 0, "Shader inventory does not navigate to events")
    task("Discover shaders and follow their uses", shader_inventory, handle is not None)
    def scoped_queries():
        markers = agent.query("pix_gpu_events", handle=handle, kind="marker", nameContains="Triangle pass", limit=1)
        scope = markers["items"][0]["eventRef"]
        events = agent.query("pix_gpu_events", handle=handle, scope=scope, limit=1000)
        event_indices = {row["eventRef"]["eventIndex"] for row in events["items"]}
        require(scope["eventIndex"] in event_indices, "Event scope omitted its root")
        timings = agent.query("pix_gpu_timing_events", handle=handle, scope=scope, kind="work", limit=1000)
        require(timings["total"] > 0 and all(row["eventRef"]["queueIndex"] == scope["queueIndex"] and
                row["eventRef"]["eventIndex"] in event_indices for row in timings["items"]), "Timing scope escaped its event subtree")
    task("Scope event and timing queries to one pass", scoped_queries, handle is not None)
    def shaped_rows():
        sizes = {}
        events = agent.query("pix_gpu_events", handle=handle, limit=1000)
        sizes["eventsObjects"] = agent.answer_bytes
        events_table = agent.query("pix_gpu_events", handle=handle, limit=1000, format="table")
        sizes["eventsTable"] = agent.answer_bytes
        agent.query("pix_gpu_events", handle=handle, limit=1000, format="table", brief=True)
        sizes["eventsBriefTable"] = agent.answer_bytes
        require(events_table["count"] == events["count"] == events["total"], "Event table rows do not match the object rows")
        require(sizes["eventsTable"] < sizes["eventsObjects"] and sizes["eventsBriefTable"] < sizes["eventsTable"],
                f"Table shaping did not shrink the {events['total']}-row event page: {sizes}")
        objects = agent.query("pix_gpu_timing_events", handle=handle, kind="work", limit=1000)
        sizes["timingObjects"] = agent.answer_bytes
        table = agent.query("pix_gpu_timing_events", handle=handle, kind="work", limit=1000, format="table")
        sizes["timingTable"] = agent.answer_bytes
        require(table["count"] == objects["count"] and len(table["rows"]) == table["count"], "Table rows do not match the object rows")
        columns = [column["name"] for column in table["columns"]]
        require(len(columns) == len(table["rows"][0]), "Table rows are not positional over columns")
        require("eop.ns" in columns and table["legend"]["refs"]["eventRef"]["kind"] == "EventRef", "Table legend lacks the EventRef recipe")
        queue_column, event_column = columns.index("queueIndex"), columns.index("eventIndex")
        rebuilt = {"handle": handle, "queueIndex": table["rows"][0][queue_column], "eventIndex": table["rows"][0][event_column]}
        inspected_row = agent.query("pix_gpu_inspect_event", eventRef=rebuilt, sections=["timing"])
        require(inspected_row["eventRef"] == rebuilt, "A table row did not rebuild a usable EventRef")
        top = agent.query("pix_gpu_timing_events", handle=handle, kind="work", topN=2, sortBy="eopDuration")
        require(top["count"] <= 2 and top.get("nextOffset") is None, "topN must not offer a continuation")
        return {"detail": {"answerBytes": sizes}}
    task("Return positional table rows and rebuild references", shaped_rows, handle is not None)
    def annotated_calls():
        overview = agent.query("pix_gpu_overview", handle=handle)
        require(all(call.get("cost") for call in overview["nextCalls"]), "Overview nextCalls lack cost hints")
        first = agent.query("pix_gpu_timing_tree", handle=handle, limit=5)
        second = agent.query("pix_gpu_timing_tree", handle=handle, limit=5)
        require(isinstance(first.get("provenance"), dict) and ("fingerprint" in first["provenance"] or "provenanceRef" in first["provenance"]), "First provenance block lacks a fingerprint")
        require(second["provenance"].get("provenanceRef") and second["provenance"].get("unchanged") is True, "Repeated provenance was not replaced by a stub")
        full = agent.query("pix_gpu_timing_tree", handle=handle, limit=5, includeProvenance=True)
        require("provenanceRef" not in full["provenance"], "includeProvenance=true must return the full block")
    task("Cost hints and provenance stubs on repeated calls", annotated_calls, handle is not None)
    def resource_uses():
        resource_ref = inspected["bindings"]["resources"][0]["resource"]["resourceRef"]
        value = agent.query("pix_gpu_resource_uses", resourceRef=resource_ref)
        require(value["total"] > 0, "Resource bindings missing")
        require(any(row["binding"].get("eventRef") for row in value["items"]), "Resource bindings lack event navigation")
        scoped = agent.query("pix_gpu_resource_uses", resourceRef=resource_ref, scope=inspected["eventRef"])
        require(all(row["binding"].get("eventRef") == inspected["eventRef"] for row in scoped["items"]), "Resource-use scope escaped the selected draw")
        resources = inspected["bindings"]["resources"]
        if len(resources) > 1:
            other_uses = agent.query("pix_gpu_resource_uses", resourceRef=resources[1]["resource"]["resourceRef"])
            require(other_uses["total"] > 0, "Second resource did not reuse navigable evidence")
    task("Follow a resource to its events", resource_uses, bool(inspected and inspected.get("bindings")))

    handles = [handle] if handle else []
    if candidate:
        other_opened = task("Open candidate capture", lambda: agent.query("pix_gpu_open", path=str(Path(candidate).resolve())))
        other = other_opened.get("handle") if other_opened else None
        if other:
            handles.append(other)
        def compare():
            value = agent.query("pix_gpu_compare", baselineHandle=handle, candidateHandle=other,
                                sections=["timings", "shaders", "pipeline", "resources"])
            require(value["matchedCount"] > 0 and value["changedCount"] > 0, "Known candidate differences were not found")
            require(value["candidateOnlyCount"] > 0, "Candidate's additional pass was not reported")
            full = agent.read(value["fullResultRef"])
            changed_sections = {field["section"] for row in full["items"] for field in row["fields"]}
            require({"shaders", "resources"} <= changed_sections, "Expected shader and resource/root-constant changes missing")
            filtered = agent.query("pix_gpu_compare_changes", fullResultRef=value["fullResultRef"], direction="regressions")
            require(all(float(row["deltaNs"]) > 0 for row in filtered["items"]), "Regression filter included a non-regression")
            with tempfile.TemporaryDirectory(prefix="pixmcp-export-") as directory:
                path = Path(directory) / "comparison.json"
                agent.query("pix_result_export", resultRef=value["fullResultRef"], outPath=str(path))
                require(json.loads(path.read_text(encoding="utf-8")) == full, "Export changed or truncated comparison data")
        task("Compare, filter and export baseline differences", compare, bool(handle and other))

    def preview():
        for opened_handle in handles:
            agent.query("pix_gpu_analysis_stop", handle=opened_handle)
        value = agent.query("pix_gpu_preview", handle=handle)
        require(value["width"] == 640 and value["height"] == 480, "Unexpected fixture preview dimensions")
        blocks = agent.call("pix_gpu_preview_image", artifactRef=value["artifactRef"])
        require(isinstance(blocks, list) and any(b.get("type") == "image" for b in blocks), "Inline preview image missing")
        cropped = agent.call("pix_gpu_preview_image", artifactRef=value["artifactRef"],
                             crop={"x": 160, "y": 120, "width": 320, "height": 240}, maxDimension=160)
        require(cropped[0]["width"] == 160 and cropped[0]["height"] == 120 and cropped[0]["resized"], "Preview crop/thumbnail dimensions are wrong")
    task("View replay output", preview, handle is not None)
    report["totalToolCalls"] = len(agent.calls)
    report["returnedJsonBytes"] = sum(c["returnedJsonBytes"] for c in agent.calls)
    report["returnedWireBytes"] = sum(c["returnedWireBytes"] or 0 for c in agent.calls)
    report["replayPreparationJobs"] = len(agent.replay_jobs)
    report["calls"] = agent.calls
    return report


def exit_status(report, strict=False, enforce_budgets=False):
    return int(any(report.get(key) for key in ("fatalError", "cleanupError", "shutdownError")) or
               report.get("serverExitCode", 0) != 0 or
               enforce_budgets and bool(report.get("budgetFailures")) or
               any(task["status"] == "failed" or strict and task["status"] != "passed" for task in report["tasks"]))


def collect_environment():
    try:
        import environment
        return environment.collect()
    except Exception as error:  # the environment block is informational
        return {"error": f"{type(error).__name__}: {error}"}


def apply_budgets(report, budgets, text_mode=None, slack=BUDGET_SLACK):
    """Records each task's budget and appends 'task: metric value > budget' to budgetFailures when over budget + slack."""
    failures = []
    for task in report["tasks"]:
        budget = budgets.get("tasks", {}).get(task["name"])
        if budget is None or task.get("status") == "skipped":
            continue
        over = [f"{metric} {task.get(field, 0)} > {limit}" for metric, field, limit in
                (("toolCalls", "toolCalls", budget.get("maxToolCalls")), ("returnedJsonBytes", "returnedJsonBytes", budget.get("maxReturnedJsonBytes")))
                if limit is not None and task.get(field, 0) > limit * (1 + slack)]
        task["budget"] = {**budget, "over": over}
        failures += [f"{task['name']}: {item}" for item in over]
    mode = text_mode or os.environ.get("PIXMCP_TEXT_CONTENT") or "full"
    json_bytes, wire_bytes = report.get("returnedJsonBytes") or 0, report.get("returnedWireBytes") or 0
    limit = budgets.get("wireToJsonRatio", {}).get(mode)
    if json_bytes:
        report["wireToJsonRatio"] = {"mode": mode, "value": round(wire_bytes / json_bytes, 3), "budget": limit}
        if limit is not None and wire_bytes / json_bytes > limit * (1 + slack):
            failures.append(f"wireToJsonRatio {wire_bytes / json_bytes:.3f} > {limit} ({mode} text content)")
    report["budgetFailures"] = failures
    return failures


def compare_baseline(report, baseline, threshold=REGRESSION_THRESHOLD):
    """Adds per-task deltas against a previous report and lists tasks whose calls or bytes grew beyond the threshold."""
    previous = {task["name"]: task for task in baseline.get("tasks", [])}
    regressions = []
    for task in report["tasks"]:
        before = previous.get(task["name"])
        if before is None or task.get("status") == "skipped":
            continue
        grew = [metric for metric in ("toolCalls", "returnedJsonBytes")
                if before.get(metric) and task.get(metric, 0) > before[metric] * (1 + threshold)]
        task["baseline"] = {"toolCalls": before.get("toolCalls"), "returnedJsonBytes": before.get("returnedJsonBytes"),
                            "deltaToolCalls": task.get("toolCalls", 0) - (before.get("toolCalls") or 0),
                            "deltaJsonBytes": task.get("returnedJsonBytes", 0) - (before.get("returnedJsonBytes") or 0),
                            "regression": grew}
        if grew:
            regressions.append(f"{task['name']}: {', '.join(grew)}")
    report["regressions"] = regressions
    return regressions


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("server")
    parser.add_argument("--capture", required=True)
    parser.add_argument("--candidate")
    parser.add_argument("--output", default="tests/artifacts/investigation-benchmark.json")
    parser.add_argument("--strict", action="store_true", help="Also fail when any task is limited or skipped.")
    parser.add_argument("--budgets", default=str(BUDGETS), help="Budget file (default scripts/benchmark-budgets.json).")
    parser.add_argument("--enforce-budgets", action="store_true", help="Fail when a task or the wire ratio exceeds its budget by more than 10 %%.")
    parser.add_argument("--baseline", help="A previous report; tasks whose calls or bytes grew by more than 25 %% are marked.")
    args = parser.parse_args()
    client = None
    result = new_report()
    result["environment"] = collect_environment()
    try:
        client = Client([args.server])
        client.send("initialize", {"protocolVersion": "2025-06-18", "capabilities": {},
                                   "clientInfo": {"name": "pixmcp-benchmark", "version": "1.0"}})
        client.send("notifications/initialized", notify=True)
        run(client, args.capture, args.candidate, result)
    except Exception as error:
        result["fatalError"] = f"{type(error).__name__}: {error}"
        print(f"Benchmark failed: {error}", file=sys.stderr)
    finally:
        try:
            if client is not None:
                try:
                    client.timeout = min(client.timeout, 10)
                    client.call("pix_close_all")
                except Exception as error:
                    result["cleanupError"] = f"{type(error).__name__}: {error}"
                    print(f"Benchmark cleanup failed: {result['cleanupError']}", file=sys.stderr)
                finally:
                    try:
                        result["serverExitCode"] = client.close()
                        if result["serverExitCode"] != 0:
                            result["shutdownError"] = f"Server exited with code {result['serverExitCode']}."
                            print(f"Benchmark shutdown failed: {result['shutdownError']}", file=sys.stderr)
                    except Exception as error:
                        result["shutdownError"] = f"{type(error).__name__}: {error}"
                        print(f"Benchmark shutdown failed: {result['shutdownError']}", file=sys.stderr)
        finally:
            try:
                if Path(args.budgets).is_file():
                    apply_budgets(result, json.loads(Path(args.budgets).read_text(encoding="utf-8")))
                if args.baseline:
                    compare_baseline(result, json.loads(Path(args.baseline).read_text(encoding="utf-8")))
            except (OSError, ValueError) as error:
                result["budgetError"] = f"{type(error).__name__}: {error}"
                result.setdefault("budgetFailures", []).append(result["budgetError"])
            output = Path(args.output)
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(json.dumps(result, indent=2), encoding="utf-8")
            print(json.dumps({"passed": sum(task["passed"] for task in result["tasks"]),
                              "limited": sum(task["status"] == "limited" for task in result["tasks"]),
                              "failed": sum(task["status"] == "failed" for task in result["tasks"]),
                              "toolCalls": result.get("totalToolCalls", 0),
                              "returnedJsonBytes": result.get("returnedJsonBytes", 0),
                              "budgetFailures": result.get("budgetFailures", []), "regressions": result.get("regressions", []),
                              "report": str(output)}, indent=2))
    return exit_status(result, args.strict, args.enforce_budgets)


if __name__ == "__main__":
    sys.exit(main())
